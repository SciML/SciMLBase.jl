end

"""
$(TYPEDEF)

Solution to a PDE, solved from a NonlinearProblem generated by a discretizer.

`PDENoTimeSolution` is the concrete wrapper for time-independent PDE
discretizations whose metadata subtypes
`AbstractDiscretizationMetadata{Val(false)}`. Discretizer packages usually
define an outer constructor `SciMLBase.PDENoTimeSolution(sol, metadata::D)` for
their metadata type `D`; the generic [`wrap_sol`](@ref SciMLBase.wrap_sol)
dispatch calls that constructor after the underlying nonlinear, linear,
optimization, or stationary solve has finished.

## Fields

  - `u`: the solution to the PDE, as a dictionary of symbols to Arrays of values. The
    Arrays are of the same shape as the domain of the PDE. Time is always the first axis.
  - `original_sol`: The original NonlinearSolution that was used to generate this solution.
  - `ivdomain`: The full list of domains for the independent variables. May be a grid for a
    discrete solution, or a vector/tuple of tuples for a continuous solution.
  - `ivs`: The list of independent variables for the solution.
  - `dvs`: The list of dependent variables for the solution.
  - `disc_data`: Metadata about the discretization process and type.
  - `prob`: The NonlinearProblem that was used to generate this solution.
  - `alg`: The algorithm used to solve the NonlinearProblem.
  - `interp`: Interpolations for the solution.
  - `retcode`: The return code from the solver. Used to determine whether the solver solved
    successfully (`sol.retcode === ReturnCode.Success`), whether it terminated due to a user-defined
    callback (`sol.retcode === ReturnCode.Terminated`), or whether it exited due to an error. For more
    details, see the return code section of the ODEProblem.jl documentation.
"""
struct PDENoTimeSolution{
        T, N, uType, Disc, Sol, domType, ivType, dvType, P, A,
        IType, S,
    } <: AbstractPDENoTimeSolution{T, N, uType, Disc}
    u::uType
    original_sol::Sol
    ivdomain::domType
    ivs::ivType
    dvs::dvType
    disc_data::Disc
    prob::P
    alg::A
    interp::IType
    retcode::ReturnCode.T
    stats::S
end

const PDESolution{
    T, N, S, D,
} = Union{
    PDETimeSeriesSolution{T, N, S, D},
    PDENoTimeSolution{T, N, S, D},
}

"""
Default callable fallback for no-time PDE wrappers.

Discretizer packages should implement this call interface for each supported
metadata type `D` when the wrapped PDE solution supports evaluation in the
original PDE variables.
"""
function (sol::PDENoTimeSolution{T, N, S, D})(args...; kwargs...) where {T, N, S, D}
    error(ArgumentError("Call for PDENoTimeSolution not implemented for solution metadata type $D, please post an issue on the relevant discretizer package's github page."))
end

"""
    wrap_sol(sol, metadata::AbstractDiscretizationMetadata)

Wrap a solver solution produced by a PDE discretizer in the appropriate PDE
solution type.

Metadata with parameter `Val(true)` is routed to
`PDETimeSeriesSolution(sol, metadata)`. Metadata with parameter `Val(false)` is
routed to `PDENoTimeSolution(sol, metadata)`. Discretizer packages are
responsible for implementing those outer constructors for their concrete
metadata types and for filling the wrapper fields from the discretized solve.
"""
function SciMLBase.wrap_sol(
        sol,
        metadata::AbstractDiscretizationMetadata{hasTime}
    ) where {
        hasTime,
    }
    if hasTime isa Val{true}
        return PDETimeSeriesSolution(sol, metadata)
    else
        return PDENoTimeSolution(sol, metadata)
    end
end

"""
    pde_index_cotangent(sol::AbstractPDESolution, sym, Δ)

Reverse-mode hook behind `sol[sym]` and `sol[sym, inds...]` (`sol[sym][inds...]` in the
interface) for a solution whose metadata
subtypes [`AbstractDifferentiableDiscretizationMetadata`](@ref SciMLBase.AbstractDifferentiableDiscretizationMetadata):
how a cotangent `Δ` of the array `sol[sym]` goes back to the solver's solution
`sol.original_sol`. It returns `nothing` when `sym` does not depend on the solve (a grid,
for instance), and otherwise a named tuple `(; u, observed)`:

  - `u`: the cotangent of `sol.original_sol.u`, of the same shape, or `nothing`;
  - `observed`: a collection of terms `(f, k, δ)` for the values the solution observes
    rather than stores, each the cotangent `δ` of
    `f(sol.original_sol.u[k], p, sol.original_sol.t[k])` with
    `p = parameter_values(sol.original_sol)`, or terms `(f, δ)` of
    `f(sol.original_sol.u, p)` when `sol.original_sol` is not a time series (an
    optimization solution, for instance).

The hook is plain code, with no AD types: the AD extensions pull the observed terms back
with the AD system in use and hand the cotangent to the solver's rules for
`original_sol`. Only the map from a field back to the solver's solution is the
discretizer's, implemented here for its metadata type `D`. `sym` is whatever the solution
was indexed with, and the metadata and the functions `f` are constants of the solve. The
fallback errors, and a hook that cannot provide a cotangent throws as well, so that a
solution never returns a wrong gradient silently.
"""
function pde_index_cotangent(
        sol::AbstractPDESolution{T, N, S, D}, sym, Δ
    ) where {T, N, S, D}
    throw(
        ArgumentError(
            "Reverse-mode differentiation of `sol[sym]` is not implemented for solution metadata type $D, please post an issue on the relevant discretizer package's github page."
        )
    )
end

"""
    pde_call_cotangent(sol::AbstractPDESolution, args, dv, Δ)

Reverse-mode hook behind `sol(args...; dv)`: a tuple of the cotangent of
`sol.original_sol`, in the form [`pde_index_cotangent`](@ref SciMLBase.pde_index_cotangent)
returns it, and the cotangents of `args`, for a cotangent `Δ` of the evaluation at `args`.
`dv` is the keyword as it was passed to the call, or `nothing` when it was not, and `Δ`
then has the shape of what the call returns in that case (a collection over `sol.dvs` in
the documented interface). The cotangents of `args` are one per argument: that of a
coordinate, or an error when the discretizer cannot provide it, and `nothing` for an index
or a colon. The fallback errors.
"""
function pde_call_cotangent(
        sol::AbstractPDESolution{T, N, S, D}, args, dv, Δ
    ) where {T, N, S, D}
    throw(
        ArgumentError(
            "Reverse-mode differentiation of `sol(args...)` is not implemented for solution metadata type $D, please post an issue on the relevant discretizer package's github page."
        )
    )
end

function Base.show(io::IO, m::MIME"text/plain", A::PDETimeSeriesSolution)
    println(io, string("retcode: ", A.retcode))
    println(io, string("Interpolation: "), typeof(A.interp))
    print(io, "t: ")
    show(io, m, A.t)
    print(io, "ivs: ")
    show(io, m, A.ivs)
    print(io, "domain:")
    show(io, m, A.ivdomain)
    println(io)
    print(io, "u: ")
    return show(io, m, A.u)
end

function Base.show(io::IO, m::MIME"text/plain", A::PDENoTimeSolution)
